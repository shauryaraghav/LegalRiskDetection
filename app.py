# ------------------------------------------------------------------ helpers
KEYWORDS = ["terminate", "termination", "penalty", "liability", "liable", "breach",
            "notice", "refund", "indemnify", "forfeit", "waive"]
_KW_RE = re.compile(r"\b(" + "|".join(KEYWORDS) + r")\b", re.IGNORECASE)


def highlight_keywords(text: str) -> str:
    """Escape user text first (prevents HTML injection), then highlight."""
    safe = html.escape(text)
    return _KW_RE.sub(r"<span style='color:#ff4d4d;font-weight:bold'>\1</span>", safe)


def render_suggestions(suggestions):
    """Suggestion text is generated from fixed templates (not user text), so it is safe markdown."""
    for sg in suggestions:
        st.markdown(f"**{sg['issue']}**  \n➡ {sg['action']}")
        st.markdown(f"> _Example wording:_ {sg['safer_wording']}")


def render_ai_box(i: int, p) -> None:
    """Optional LLM explanation for one clause (only runs when the user clicks)."""
    if not ai_enabled:
        return
    if st.button("🤖 Explain with AI", key=f"ai_btn_{i}"):
        with st.spinner("Asking the AI…"):
            st.session_state.setdefault("ai", {})[i] = explain_clause(
                p.clause, p.category, p.risk, p.reasons, api_key=ai_key or None)
    out = st.session_state.get("ai", {}).get(i)
    if out:
        if out["ok"]:
            st.markdown("**AI explanation**  \n" + md_escape(out["explanation"]))
            if out["suggested_wording"]:
                st.markdown("> _Suggested wording:_ " + md_escape(out["suggested_wording"]))
            st.caption(f"Generated by {out['model']} · not legal advice")
        else:
            st.warning(out["error"])


def render_feedback_form(i: int, p) -> None:
    """Let the user correct a wrong prediction; corrections are used when retraining."""
    with st.expander(f"✏ Wrong prediction for clause {i}? Correct it"):
        with st.form(f"fb_{i}"):
            cat = st.selectbox("Correct category", CATEGORIES, key=f"fbc_{i}",
                               index=CATEGORIES.index(p.category) if p.category in CATEGORIES else 0)
            risk = st.selectbox("Correct risk level", RISK_LEVELS, key=f"fbr_{i}", index=RISK_LEVELS.index(p.risk))
            if st.form_submit_button("Save correction"):
                try:
                    save_feedback(p.clause, cat, risk, p.category, p.risk)
                    st.success("Saved. Open **Model Evaluation → Retrain** to apply your corrections.")
                except ValueError as exc:
                    st.error(str(exc))


